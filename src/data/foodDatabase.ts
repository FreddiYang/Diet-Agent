import { Ingredient, MealCategory } from '../types';
import { roundToTwo, formatNum } from '../utils/formatters';

export interface GraphicFoodItem {
  id: string;
  name: string;
  icon: string;
  category: MealCategory;
  portion: string;
  weightGrams: number;
  calories: number;
  protein: number;
  carbs: number;
  fat: number;
  fiber: number;
  sodium: number;
  sugar: number;
  tag: string;
  isComfort?: boolean;
}

// Calculate precise nutrition based on weight in grams with at most 2 decimal digits behind the '.'
export function calculateIngredientNutrition(ingredient: Ingredient, weightGrams: number) {
  const roundedWeight = roundToTwo(weightGrams);
  const factor = roundedWeight / 100;
  const ratio = roundToTwo(roundedWeight / ingredient.suggestedGrams);
  return {
    weightGrams: roundedWeight,
    portion: `${formatNum(roundedWeight)}g (${formatNum(ratio)}x ${ingredient.suggestedUnit})`,
    calories: roundToTwo(ingredient.per100g.calories * factor),
    protein: roundToTwo(ingredient.per100g.protein * factor),
    carbs: roundToTwo(ingredient.per100g.carbs * factor),
    fat: roundToTwo(ingredient.per100g.fat * factor),
    fiber: roundToTwo(ingredient.per100g.fiber * factor),
    sodium: roundToTwo(ingredient.per100g.sodium * factor),
    sugar: roundToTwo(ingredient.per100g.sugar * factor),
  };
}

